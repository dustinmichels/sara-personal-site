// Bubbles on home page
if (document.body.classList.contains('is-home')) {
  const container = document.querySelector('.hero-photo-wrapper');
  if (container) {
    const spawnBubble = () => {
      const b = document.createElement('div');
      b.className = 'bubble';
      const size = Math.random() * 24 + 6;
      b.style.width = size + 'px';
      b.style.height = size + 'px';
      b.style.left = Math.random() * 95 + '%';
      b.style.animationDuration = Math.random() * 6 + 4 + 's';
      container.appendChild(b);
      b.addEventListener('animationend', () => b.remove(), { once: true });
      setTimeout(spawnBubble, Math.random() * 1200 + 400);
    };
    spawnBubble();
  }
}

// Scroll-based header background
